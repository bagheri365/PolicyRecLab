from __future__ import annotations

from dataclasses import dataclass
import numpy as np
from numpy.typing import NDArray

from policyreclab.datasets.mnar_ratings import RatingTriples
from policyreclab.experiments.mnar_debiasing import (
    inverse_item_frequency_propensities,
)

FloatArray = NDArray[np.float64]


@dataclass(frozen=True)
class ExposureWeightDiagnostics:
    maximum_weight: float
    p99_weight: float
    effective_sample_size: float
    effective_sample_fraction: float


@dataclass(frozen=True)
class CoatExposureComparison:
    randomized_reference_mean: float
    naive_observational_mean: float
    item_frequency_mean: float
    matrix_factorization_mean: float
    naive_bias: float
    item_frequency_bias: float
    matrix_factorization_bias: float
    item_frequency_bias_reduction: float
    matrix_factorization_bias_reduction: float
    item_frequency_diagnostics: ExposureWeightDiagnostics
    matrix_factorization_diagnostics: ExposureWeightDiagnostics
    n_folds: int
    rank: int
    min_propensity: float


def _sigmoid(x: FloatArray) -> FloatArray:
    x = np.clip(x, -30.0, 30.0)
    return 1.0 / (1.0 + np.exp(-x))


def _fit_logistic_matrix_factorization(
    observation_matrix: FloatArray,
    train_mask: NDArray[np.bool_],
    *,
    rank: int,
    epochs: int,
    learning_rate: float,
    l2: float,
    seed: int,
) -> FloatArray:
    """Fit a regularized logistic low-rank exposure model on pair labels."""
    n_users, n_items = observation_matrix.shape
    rng = np.random.default_rng(seed)

    global_rate = float(
        np.mean(observation_matrix[train_mask])
    )
    global_rate = float(np.clip(global_rate, 1e-4, 1.0 - 1e-4))
    intercept = np.log(global_rate / (1.0 - global_rate))

    user_bias = np.zeros(n_users, dtype=np.float64)
    item_bias = np.zeros(n_items, dtype=np.float64)
    user_factors = rng.normal(0.0, 0.02, size=(n_users, rank))
    item_factors = rng.normal(0.0, 0.02, size=(n_items, rank))

    mask = train_mask.astype(np.float64)
    denom = max(1.0, float(np.sum(mask)))

    for _ in range(epochs):
        logits = (
            intercept
            + user_bias[:, None]
            + item_bias[None, :]
            + user_factors @ item_factors.T
        )
        probabilities = _sigmoid(logits)
        residual = (probabilities - observation_matrix) * mask

        grad_intercept = float(np.sum(residual) / denom)
        grad_user_bias = np.sum(residual, axis=1) / denom + l2 * user_bias
        grad_item_bias = np.sum(residual, axis=0) / denom + l2 * item_bias
        grad_user_factors = (
            residual @ item_factors / denom + l2 * user_factors
        )
        grad_item_factors = (
            residual.T @ user_factors / denom + l2 * item_factors
        )

        intercept -= learning_rate * grad_intercept
        user_bias -= learning_rate * grad_user_bias
        item_bias -= learning_rate * grad_item_bias
        user_factors -= learning_rate * grad_user_factors
        item_factors -= learning_rate * grad_item_factors

    logits = (
        intercept
        + user_bias[:, None]
        + item_bias[None, :]
        + user_factors @ item_factors.T
    )
    return _sigmoid(logits)


def cross_fitted_exposure_propensities(
    observational: RatingTriples,
    *,
    n_users: int,
    n_items: int,
    n_folds: int = 5,
    rank: int = 4,
    epochs: int = 80,
    learning_rate: float = 8.0,
    l2: float = 1e-3,
    min_propensity: float = 0.01,
    seed: int = 2026,
) -> FloatArray:
    """Estimate P(O_ui=1) with pair-level cross-fitted logistic MF.

    Every user-item pair is labeled observed/not-observed from the
    observational matrix. Predictions for a pair are generated by a model that
    did not train on that pair's observation label.
    """
    if n_folds < 2:
        raise ValueError("n_folds must be at least 2")
    if rank < 1:
        raise ValueError("rank must be positive")
    if not 0.0 < min_propensity < 1.0:
        raise ValueError("min_propensity must lie in (0, 1)")

    observed = np.zeros((n_users, n_items), dtype=np.float64)
    observed[observational.users, observational.items] = 1.0

    rng = np.random.default_rng(seed)
    fold_ids = rng.integers(
        0, n_folds, size=(n_users, n_items), dtype=np.int64
    )
    predictions = np.empty_like(observed)

    for fold in range(n_folds):
        test_mask = fold_ids == fold
        train_mask = ~test_mask
        fitted = _fit_logistic_matrix_factorization(
            observed,
            train_mask,
            rank=rank,
            epochs=epochs,
            learning_rate=learning_rate,
            l2=l2,
            seed=seed + fold + 1,
        )
        predictions[test_mask] = fitted[test_mask]

    observed_propensities = predictions[
        observational.users, observational.items
    ]
    return np.clip(
        observed_propensities,
        min_propensity,
        1.0,
    ).astype(np.float64)


def _weighted_mean(
    ratings: FloatArray,
    propensities: FloatArray,
) -> tuple[float, ExposureWeightDiagnostics]:
    weights = 1.0 / propensities
    estimate = float(np.sum(weights * ratings) / np.sum(weights))
    ess = float(np.sum(weights) ** 2 / np.sum(weights ** 2))
    diagnostics = ExposureWeightDiagnostics(
        maximum_weight=float(np.max(weights)),
        p99_weight=float(np.quantile(weights, 0.99)),
        effective_sample_size=ess,
        effective_sample_fraction=float(ess / ratings.size),
    )
    return estimate, diagnostics


def run_coat_exposure_comparison(
    *,
    observational: RatingTriples,
    randomized: RatingTriples,
    n_users: int = 290,
    n_items: int = 300,
    n_folds: int = 5,
    rank: int = 4,
    epochs: int = 80,
    learning_rate: float = 8.0,
    l2: float = 1e-3,
    min_propensity: float = 0.01,
    seed: int = 2026,
) -> CoatExposureComparison:
    """Compare item-frequency and cross-fitted user-item exposure models."""
    reference = float(np.mean(randomized.ratings))
    naive = float(np.mean(observational.ratings))

    item_p = inverse_item_frequency_propensities(
        observational,
        n_users=n_users,
        n_items=n_items,
    )[observational.items]
    item_mean, item_diag = _weighted_mean(
        observational.ratings,
        item_p,
    )

    mf_p = cross_fitted_exposure_propensities(
        observational,
        n_users=n_users,
        n_items=n_items,
        n_folds=n_folds,
        rank=rank,
        epochs=epochs,
        learning_rate=learning_rate,
        l2=l2,
        min_propensity=min_propensity,
        seed=seed,
    )
    mf_mean, mf_diag = _weighted_mean(
        observational.ratings,
        mf_p,
    )

    naive_bias = naive - reference
    item_bias = item_mean - reference
    mf_bias = mf_mean - reference

    def bias_reduction(candidate_bias: float) -> float:
        if naive_bias == 0.0:
            return float("nan")
        return float(1.0 - abs(candidate_bias) / abs(naive_bias))

    return CoatExposureComparison(
        randomized_reference_mean=reference,
        naive_observational_mean=naive,
        item_frequency_mean=item_mean,
        matrix_factorization_mean=mf_mean,
        naive_bias=naive_bias,
        item_frequency_bias=item_bias,
        matrix_factorization_bias=mf_bias,
        item_frequency_bias_reduction=bias_reduction(item_bias),
        matrix_factorization_bias_reduction=bias_reduction(mf_bias),
        item_frequency_diagnostics=item_diag,
        matrix_factorization_diagnostics=mf_diag,
        n_folds=n_folds,
        rank=rank,
        min_propensity=min_propensity,
    )
